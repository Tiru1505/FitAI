import { useState } from "react";
import { Link } from "react-router-dom";

import { errorMessage } from "../api/client";
import { useActivePlan, useGeneratePlan } from "../api/hooks";
import { label, type PlannedExercise } from "../api/types";
import { CalendarIcon, ExerciseMark, SparkIcon } from "../components/icons";
import { Alert, Button, Card, PageHeader, Spinner } from "../components/ui";

function ExerciseRow({ pe }: { pe: PlannedExercise }) {
  const [open, setOpen] = useState(false);
  return (
    <li className="py-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <button
          type="button"
          className="flex items-center gap-3 text-left font-medium text-beige-100 transition-colors hover:text-plum-300"
          aria-expanded={open}
          onClick={() => setOpen((o) => !o)}
        >
          <span className="grid h-9 w-9 place-items-center rounded-lg bg-plum-500/12 text-plum-300 [&>svg]:h-5 [&>svg]:w-5">
            <ExerciseMark slug={pe.exercise.slug} />
          </span>
          {pe.exercise.name}
          <span className={`text-xs text-beige-500 transition-transform duration-300 ${open ? "rotate-180" : ""}`}>▾</span>
        </button>
        <div className="flex items-center gap-2 text-sm tabular-nums text-beige-300">
          {pe.practice_mode && <span className="rounded bg-ember-500/20 px-2 py-0.5 text-xs text-ember-300">Practice mode</span>}
          <span>{pe.sets} sets × {pe.repetitions} reps</span>
          <span className="text-beige-500">·</span>
          <span>{pe.rest_seconds}s rest</span>
        </div>
      </div>
      {pe.notes && <p className="mt-1 text-sm text-ember-300">{pe.notes}</p>}
      {open && (
        <div className="animate-fade-up mt-3 grid gap-4 rounded-xl bg-gradient-to-br from-plum-500/15/70 to-transparent p-4 text-sm md:grid-cols-3">
          <div>
            <p className="mb-1 font-medium text-beige-200">Instructions</p>
            <ol className="list-decimal space-y-1 pl-5 text-beige-300">{pe.exercise.instructions.map((s) => <li key={s}>{s}</li>)}</ol>
          </div>
          <div>
            <p className="mb-1 font-medium text-beige-200">Form cues</p>
            <ul className="list-disc space-y-1 pl-5 text-beige-300">{pe.exercise.form_cues.map((s) => <li key={s}>{s}</li>)}</ul>
            <p className="mt-3 mb-1 font-medium text-beige-200">Muscles</p>
            <p className="text-beige-300">{pe.exercise.muscle_group}</p>
          </div>
          <div>
            <p className="mb-1 font-medium text-beige-200">Substitutions</p>
            <ul className="list-disc space-y-1 pl-5 text-beige-300">{pe.exercise.substitutions.map((s) => <li key={s}>{s}</li>)}</ul>
            <p className="mt-3 text-xs text-beige-400">{pe.exercise.safety_note}</p>
          </div>
        </div>
      )}
    </li>
  );
}

export default function WorkoutPlanPage() {
  const plan = useActivePlan();
  const generate = useGeneratePlan();

  if (plan.isLoading) return <Spinner />;
  if (plan.isError) return <Alert tone="error">{errorMessage(plan.error)}</Alert>;
  if (!plan.data) {
    return (
      <Card title="No plan yet">
        <p className="mb-3 text-sm text-beige-300">Complete your profile to generate a plan.</p>
        <Link to="/profile"><Button>Go to profile</Button></Link>
      </Card>
    );
  }
  const p = plan.data;

  return (
    <div className="space-y-6">
      <PageHeader
        title="Workout plan"
        subtitle={`${label(p.template)} · version ${p.version} · ${p.days_per_week} days/week`}
        action={
          <div className="flex gap-2">
            <Link to="/profile"><Button variant="secondary">Edit preferences</Button></Link>
            <Button variant="secondary" disabled={generate.isPending} onClick={() => generate.mutate()}>
              {generate.isPending ? "Regenerating…" : "Regenerate"}
            </Button>
          </div>
        }
      />
      {generate.isError && <Alert tone="error">{errorMessage(generate.error)}</Alert>}
      {p.warnings.map((w) => <Alert key={w} tone="warning">{w}</Alert>)}

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="space-y-4 lg:col-span-2">
          {p.days.map((day) => (
            <Card key={day.day_index} icon={<CalendarIcon />} title={`${day.weekday_name} — Day ${day.day_index + 1}`}>
              <ul className="divide-y divide-white/8">{day.exercises.map((pe) => <ExerciseRow key={pe.id} pe={pe} />)}</ul>
            </Card>
          ))}
        </div>
        <Card title="Why this plan?" icon={<SparkIcon />}>
          <ul className="space-y-2 text-sm text-beige-300">
            {p.generated_reason.split("\n").filter(Boolean).map((line, i) => <li key={i}>{line}</li>)}
          </ul>
          <p className="mt-4 text-xs text-beige-500">
            Generated by transparent rules from your goal, experience, equipment, schedule and exclusions. Plans adapt after
            each completed session; see adaptation history on the Progress page.
          </p>
        </Card>
      </div>
    </div>
  );
}
